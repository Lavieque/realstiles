export default function AnnouncementBar() {
  const [itens, setItens] = useState<ItemAnuncio[]>([]);

  useEffect(() => {
    fetch('/api/config/anuncios')
      .then(r => r.json())
      .then(d => setItens(d.itens || []))
      .catch(() => {});
  }, []);

  if (!itens.length) return null;

  const duplicated = [...itens, ...itens];

  return (
    <div className="announcement-bar">
      <div className="announcement-track">
        {duplicated.map((item, i) => (
          <span key={i} className="announcement-item">
            {item.icone && ICONES_SVG[item.icone] && (
              <span className="announcement-icon">{ICONES_SVG[item.icone]}</span>
            )}
            {item.texto}
          </span>
        ))}
      </div>
    </div>
  );
}
